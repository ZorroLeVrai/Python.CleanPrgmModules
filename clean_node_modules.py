"""Recursively delete node_modules folders that sit next to a package.json file."""

import argparse
import os
import shutil
import sys

ROOT_DIR = r""
ROOT_DIR_FROM_ENV = "prgm"
NODE_MODULES_DIRNAME = "node_modules"
PACKAGE_JSON_FILENAME = "package.json"


def resolve_root_dir() -> str:
    if ROOT_DIR:
        return ROOT_DIR
    return os.environ.get(ROOT_DIR_FROM_ENV, "")


def find_node_modules_to_delete(root_dir: str) -> list[str]:
    targets: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root_dir):
        if NODE_MODULES_DIRNAME in dirnames and PACKAGE_JSON_FILENAME in filenames:
            targets.append(os.path.join(dirpath, NODE_MODULES_DIRNAME))
            # Don't descend into the node_modules folder we're about to remove.
            dirnames.remove(NODE_MODULES_DIRNAME)
    return targets


def get_folder_size_bytes(folder_path: str) -> int:
    total_size = 0
    for dirpath, _, filenames in os.walk(folder_path):
        for filename in filenames:
            file_path = os.path.join(dirpath, filename)
            try:
                total_size += os.path.getsize(file_path)
            except OSError:
                pass
    return total_size


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Delete node_modules folders that are siblings of a package.json file."
    )
    parser.add_argument(
        "--test",
        action="store_true",
        help="Dry run: list what would be deleted without deleting anything.",
    )
    args, unknown_args = parser.parse_known_args()

    if unknown_args:
        print(f"Unknown argument(s): {' '.join(unknown_args)}", file=sys.stderr)
        sys.exit(1)

    root_dir = resolve_root_dir()

    if not root_dir:
        print(
            f"No root directory set. Set the ROOT_DIR constant or the "
            f"{ROOT_DIR_FROM_ENV} environment variable.",
            file=sys.stderr,
        )
        sys.exit(1)

    if not os.path.isdir(root_dir):
        print(f"Root directory not found: {root_dir}", file=sys.stderr)
        sys.exit(1)

    if not args.test:
        answer = input(
            f"Warning: you are about to delete all {NODE_MODULES_DIRNAME} folders "
            f"under {root_dir}. Continue? [y/N] "
        )
        if answer.strip().lower() not in ("y", "yes"):
            print("Aborted.")
            return

    targets = find_node_modules_to_delete(root_dir)

    if not targets:
        print("No node_modules folders found.")
        return

    total_size_bytes = 0

    for target in targets:
        size_bytes = get_folder_size_bytes(target)
        size_mb = size_bytes / (1024 * 1024)

        if args.test:
            print(f"[TEST] Would delete: {target} ({size_mb:.2f} MB)")
            total_size_bytes += size_bytes
        else:
            try:
                shutil.rmtree(target)
                print(f"Deleted: {target} ({size_mb:.2f} MB)")
                total_size_bytes += size_bytes
            except OSError as exc:
                print(f"Failed to delete {target}: {exc}", file=sys.stderr)

    total_size_mb = total_size_bytes / (1024 * 1024)
    verb = "Would delete" if args.test else "Deleted"
    saved_verb = "would be saved" if args.test else "saved"
    print(f"\n{verb} {len(targets)} node_modules folder(s).")
    print(f"Total space {saved_verb}: {total_size_mb:,.2f} MB")


if __name__ == "__main__":
    main()
