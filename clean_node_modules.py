"""Recursively delete node_modules and .venv folders that sit next to their project marker file."""

import argparse
import os
import shutil
import sys

ROOT_DIR = r""
ROOT_DIR_FROM_ENV = "prgm"

NODE_MODULES_DIRNAME = "node_modules"
PACKAGE_JSON_FILENAME = "package.json"

VENV_DIRNAME = ".venv"
PYTHON_MARKER_FILENAMES = ("requirements.txt", "pyproject.toml")


def resolve_root_dir() -> str:
    if ROOT_DIR:
        return ROOT_DIR
    return os.environ.get(ROOT_DIR_FROM_ENV, "")


def find_folders_to_delete(
    root_dir: str, target_dirname: str, marker_filenames: tuple[str, ...]
) -> list[str]:
    targets: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root_dir):
        if target_dirname in dirnames and any(
            marker in filenames for marker in marker_filenames
        ):
            targets.append(os.path.join(dirpath, target_dirname))
            # Don't descend into the folder we're about to remove.
            dirnames.remove(target_dirname)
    return targets


def get_folder_size_bytes(folder_path: str) -> int:
    total_size = 0
    for dirpath, _, filenames in os.walk(folder_path):
        for filename in filenames:
            file_path = os.path.join(dirpath, filename)
            try:
                total_size += os.path.getsize(file_path)
            except OSError:
                pass
    return total_size


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Delete node_modules folders (siblings of package.json) and/or "
            ".venv folders (siblings of requirements.txt or pyproject.toml)."
        )
    )
    parser.add_argument(
        "--test",
        action="store_true",
        help="Dry run: list what would be deleted without deleting anything.",
    )
    parser.add_argument(
        "--js",
        "--javascript",
        action="store_true",
        dest="js",
        help="Only remove node_modules folders.",
    )
    parser.add_argument(
        "--py",
        "--python",
        action="store_true",
        dest="py",
        help="Only remove .venv folders.",
    )
    args, unknown_args = parser.parse_known_args()

    if unknown_args:
        print(f"Unknown argument(s): {' '.join(unknown_args)}", file=sys.stderr)
        sys.exit(1)

    root_dir = resolve_root_dir()

    if not root_dir:
        print(
            f"No root directory set. Set the ROOT_DIR constant or the "
            f"{ROOT_DIR_FROM_ENV} environment variable.",
            file=sys.stderr,
        )
        sys.exit(1)

    if not os.path.isdir(root_dir):
        print(f"Root directory not found: {root_dir}", file=sys.stderr)
        sys.exit(1)

    # Default to both when neither --js nor --py is given.
    include_js = args.js or not args.py
    include_py = args.py or not args.js

    dir_labels = []
    if include_js:
        dir_labels.append(NODE_MODULES_DIRNAME)
    if include_py:
        dir_labels.append(VENV_DIRNAME)
    folders_description = " and ".join(dir_labels)

    if not args.test:
        answer = input(
            f"Warning: you are about to delete all {folders_description} folders "
            f"under {root_dir}. Continue? [y/N] "
        )
        if answer.strip().lower() not in ("y", "yes"):
            print("Aborted.")
            return

    targets: list[str] = []
    if include_js:
        targets += find_folders_to_delete(
            root_dir, NODE_MODULES_DIRNAME, (PACKAGE_JSON_FILENAME,)
        )
    if include_py:
        targets += find_folders_to_delete(root_dir, VENV_DIRNAME, PYTHON_MARKER_FILENAMES)

    if not targets:
        print(f"No {folders_description} folders found.")
        return

    total_size_bytes = 0

    for target in targets:
        size_bytes = get_folder_size_bytes(target)
        size_mb = size_bytes / (1024 * 1024)

        if args.test:
            print(f"[TEST] Would delete: {target} ({size_mb:.2f} MB)")
            total_size_bytes += size_bytes
        else:
            try:
                shutil.rmtree(target)
                print(f"Deleted: {target} ({size_mb:.2f} MB)")
                total_size_bytes += size_bytes
            except OSError as exc:
                print(f"Failed to delete {target}: {exc}", file=sys.stderr)

    total_size_mb = total_size_bytes / (1024 * 1024)
    verb = "Would delete" if args.test else "Deleted"
    saved_verb = "would be saved" if args.test else "saved"
    print(f"\n{verb} {len(targets)} folder(s).")
    print(f"Total space {saved_verb}: {total_size_mb:,.2f} MB")


if __name__ == "__main__":
    main()
