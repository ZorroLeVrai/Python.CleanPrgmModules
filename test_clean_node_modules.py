def test_main_test_mode_lists_targets_without_deleting(
    mocker: MockerFixture, capsys: pytest.CaptureFixture[str]
) -> None:
    mocker.patch("clean_node_modules.sys.argv", ["clean_node_modules.py", "--all", "--test"])
    mocker.patch("clean_node_modules.resolve_root_dir", return_value=r"E:\root")
    mocker.patch("clean_node_modules.os.path.isdir", return_value=True)
    mocker.patch(
        "clean_node_modules.find_folders_to_delete",
        side_effect=[
            [r"E:\root\project_a\node_modules"],
            [r"E:\root\project_b\.venv"],
        ],
    )
    mocker.patch("clean_node_modules.get_folder_size_bytes", return_value=1024 * 1024)
    rmtree = mocker.patch("clean_node_modules.shutil.rmtree")

    clean_node_modules.main()

    rmtree.assert_not_called()
    out = capsys.readouterr().out
    assert "[TEST] Would delete: E:\\root\\project_a\\node_modules (1.00 MB)" in out
    assert "[TEST] Would delete: E:\\root\\project_b\\.venv (1.00 MB)" in out
    assert "Would delete 2 folder(s)." in out
    assert "Total space would be saved: 2.00 MB" in out


