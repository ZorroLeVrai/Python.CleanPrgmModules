"""Unit tests for clean_node_modules.py, using pytest-mock to simulate directories."""

import pytest
from pytest_mock import MockerFixture

import clean_node_modules


# --- resolve_root_dir ---------------------------------------------------


def test_resolve_root_dir_uses_root_dir_constant_when_set(
    mocker: MockerFixture,
) -> None:
    mocker.patch.object(clean_node_modules, "ROOT_DIR", r"C:\some\configured\path")
    mocker.patch.dict(
        clean_node_modules.os.environ, {clean_node_modules.ROOT_DIR_FROM_ENV: r"C:\env\path"}
    )

    assert clean_node_modules.resolve_root_dir() == r"C:\some\configured\path"


def test_resolve_root_dir_falls_back_to_env_var_when_root_dir_empty(
    mocker: MockerFixture,
) -> None:
    mocker.patch.object(clean_node_modules, "ROOT_DIR", "")
    mocker.patch.dict(
        clean_node_modules.os.environ, {clean_node_modules.ROOT_DIR_FROM_ENV: r"C:\env\path"}
    )

    assert clean_node_modules.resolve_root_dir() == r"C:\env\path"


def test_resolve_root_dir_returns_empty_when_neither_is_set(
    mocker: MockerFixture,
) -> None:
    mocker.patch.object(clean_node_modules, "ROOT_DIR", "")
    mocker.patch.dict(clean_node_modules.os.environ, {}, clear=True)

    assert clean_node_modules.resolve_root_dir() == ""


# --- find_folders_to_delete ----------------------------------------------


def test_find_folders_to_delete_matches_node_modules_sibling_to_package_json(
    mocker: MockerFixture,
) -> None:
    walk_data = [
        (r"root", ["project_a", "project_b"], []),
        (r"root\project_a", ["node_modules"], ["package.json"]),
        (r"root\project_b", ["node_modules"], []),  # no package.json -> not a match
    ]
    mocker.patch("clean_node_modules.os.walk", return_value=iter(walk_data))

    targets = clean_node_modules.find_folders_to_delete(
        "root", clean_node_modules.NODE_MODULES_DIRNAME, (clean_node_modules.PACKAGE_JSON_FILENAME,)
    )

    assert targets == [r"root\project_a\node_modules"]


def test_find_folders_to_delete_matches_any_of_several_marker_filenames(
    mocker: MockerFixture,
) -> None:
    walk_data = [
        (r"root\project_a", [".venv"], ["requirements-dev.txt"]),
    ]
    mocker.patch("clean_node_modules.os.walk", return_value=iter(walk_data))

    targets = clean_node_modules.find_folders_to_delete(
        "root", clean_node_modules.VENV_DIRNAME, clean_node_modules.PYTHON_MARKER_FILENAMES
    )

    assert targets == [r"root\project_a\.venv"]


def test_find_folders_to_delete_prunes_matched_dir_from_dirnames(
    mocker: MockerFixture,
) -> None:
    dirnames = ["node_modules", "src"]
    walk_data = [(r"root\project_a", dirnames, ["package.json"])]
    mocker.patch("clean_node_modules.os.walk", return_value=iter(walk_data))

    clean_node_modules.find_folders_to_delete(
        "root", clean_node_modules.NODE_MODULES_DIRNAME, (clean_node_modules.PACKAGE_JSON_FILENAME,)
    )

    assert "node_modules" not in dirnames


# --- get_folder_size_bytes ------------------------------------------------


def test_get_folder_size_bytes_sums_all_file_sizes(mocker: MockerFixture) -> None:
    walk_data = [
        (r"root", [], ["a.txt", "b.txt"]),
        (r"root\sub", [], ["c.txt"]),
    ]
    mocker.patch("clean_node_modules.os.walk", return_value=iter(walk_data))

    sizes = {
        r"root\a.txt": 100,
        r"root\b.txt": 250,
        r"root\sub\c.txt": 50,
    }
    mocker.patch(
        "clean_node_modules.os.path.getsize", side_effect=lambda path: sizes[path]
    )

    assert clean_node_modules.get_folder_size_bytes("root") == 400


def test_get_folder_size_bytes_skips_files_that_raise_oserror(
    mocker: MockerFixture,
) -> None:
    walk_data = [(r"root", [], ["a.txt", "broken.txt"])]
    mocker.patch("clean_node_modules.os.walk", return_value=iter(walk_data))

    def fake_getsize(path: str) -> int:
        if path.endswith("broken.txt"):
            raise OSError("permission denied")
        return 100

    mocker.patch("clean_node_modules.os.path.getsize", side_effect=fake_getsize)

    assert clean_node_modules.get_folder_size_bytes("root") == 100


