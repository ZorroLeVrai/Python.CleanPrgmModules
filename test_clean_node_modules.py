def test_main_real_mode_deletes_targets_after_confirmation(
    mocker: MockerFixture, capsys: pytest.CaptureFixture[str]
) -> None:
    mocker.patch("clean_node_modules.sys.argv", ["clean_node_modules.py", "--all"])
    mocker.patch("clean_node_modules.resolve_root_dir", return_value=r"E:\root")
    mocker.patch("clean_node_modules.os.path.isdir", return_value=True)
    mocker.patch(
        "clean_node_modules.find_folders_to_delete",
        side_effect=[[r"E:\root\project_a\node_modules"], []],
    )
    mocker.patch("clean_node_modules.get_folder_size_bytes", return_value=1024 * 1024)
    mocker.patch("clean_node_modules.input", return_value="y")
    rmtree = mocker.patch("clean_node_modules.shutil.rmtree")

    clean_node_modules.main()

    rmtree.assert_called_once_with(r"E:\root\project_a\node_modules")
    out = capsys.readouterr().out
    assert "Deleted: E:\\root\\project_a\\node_modules (1.00 MB)" in out
    assert "Total space saved: 1.00 MB" in out


